; Generates chr/chr_map.js
; chr_map.js is a diff between the extract chr files and the vanilla game and builds out the mapping
; that we can commit. Call this project with
;   js65 build -p gen_chr_map.json
; It won't overwrite an existing chr/chr_map.js, so delete that first to regenerate it.
; Files with no rom tiles at all (custom art) are left out since they are safe to commit.

.segment "CHR_MAP_OUT" :mem 0 :size $100000 :off 0 :out "chr/chr_map.js"

.jsinput chrfiles, "chr/*.chr"
.jsinput roms, "*.nes"
; Use a glob file so that if the chr map is missing we don't get an error
.jsinput chrmapfile, "chr/chr_map*.js"
.jsinclude "src/gen/chr_tools.js"
.jsbegin

const CONSTANTS = {
  SPR: 0x000,
  BG: 0x100,
  FLIP_H: 0x200,
  FLIP_V: 0x400,
  FLIP_HV: 0x600,
  SHIFT_DOWN4: 0x800,
  SHIFT_UP4: 0x1000,
};
const {SPR, BG, FLIP_H, FLIP_V, FLIP_HV, SHIFT_DOWN4, SHIFT_UP4} = CONSTANTS;

const hex = n => "0x" + n.toString(16).padStart(2, "0");

function formatEntry(e) {
  if (Array.isArray(e)) return "[" + e.map(hex).join(", ") + "]";
  const parts = [(e & BG) ? "BG" : "SPR", hex(e & 0xff)];
  if ((e & FLIP_HV) === FLIP_HV) parts.push("FLIP_HV");
  else if (e & FLIP_H) parts.push("FLIP_H");
  else if (e & FLIP_V) parts.push("FLIP_V");
  if (e & SHIFT_DOWN4) parts.push("SHIFT_DOWN4");
  if (e & SHIFT_UP4) parts.push("SHIFT_UP4");
  return parts.join("|");
}

// Builds the chr_map.js source text for every chr file by finding each tile in the rom
function genChrMap(romChr, files) {
  // Plain tiles are preferred over flips, and flips over shifts, so the simplest match wins
  const transforms = [0, FLIP_H, FLIP_V, FLIP_HV];
  for (const shift of [SHIFT_DOWN4, SHIFT_UP4]) transforms.push(...transforms.map(t => t | shift));
  const lookup = {};
  for (const table of [SPR, BG]) {
    lookup[table] = new Map();
    for (const t of transforms) {
      for (let id = 0; id < 256; id++) {
        const key = buildTile(romChr, table | id | t).join();
        if (!lookup[table].has(key)) lookup[table].set(key, table | id | t);
      }
    }
  }

  const blank = new Uint8Array(16).join();
  const custom = [];
  let body = "";
  for (const f of [...files].sort((x, y) => x.path < y.path ? -1 : 1)) {
    const name = f.path.split(/[\\/]/).pop().replace(/\.chr$/, "");
    const tiles = [];
    for (let i = 0; i + 16 <= f.bytes.length; i += 16) tiles.push(Array.from(f.bytes.subarray(i, i + 16)));
    const keys = tiles.map(t => t.join());
    // Use the pattern table most of the file comes from, so blank tiles etc match it
    const count = table => keys.filter(k => lookup[table].has(k)).length;
    const [first, second] = count(BG) > count(SPR) ? [BG, SPR] : [SPR, BG];
    const entries = keys.map((k, i) => lookup[first].get(k) ?? lookup[second].get(k) ?? tiles[i]);

    if (!keys.some((k, i) => k !== blank && !Array.isArray(entries[i]))) {
      custom.push(name);
      continue;
    }
    const literals = entries.filter(e => Array.isArray(e)).length;
    if (literals) body += `  // ${name} has ${literals} custom tiles, consider moving them to their own file\n`;
    body += `  ${name}: [\n`;
    for (let i = 0; i < entries.length; i += 16) {
      body += "    " + entries.slice(i, i + 16).map(formatEntry).join(", ") + ",\n";
    }
    body += "  ],\n";
  }
  let text = "// Generated by src/gen/gen_chr_map.s, run: js65 build -p gen_chr_map.json\n";
  if (custom.length) text += `// Custom files with no rom tiles, commit these directly: ${custom.join(", ")}\n`;
  for (const [k, v] of Object.entries(CONSTANTS)) text += `const ${k} = 0x${v.toString(16).padStart(3, "0")};\n`;
  return text + "\nconst CHR_MAP = {\n" + body + "};\n";
}

if (chrmapfile.length) throw new Error("chr/chr_map.js already exists, delete it first to regenerate it");
const romChr = findSmb1Chr(roms);
if (!romChr) throw new Error("Couldn't find a Super Mario Bros. (World) rom in the project root");
a.segment("CHR_MAP_OUT");
a.org(0);
a.byte(Array.from(genChrMap(romChr, chrfiles), c => c.charCodeAt(0)));
.jsend
